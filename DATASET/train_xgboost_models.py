"""
=============================================================================
AEROTWIN-4 XGBOOST FAULT CLASSIFIER — RETRAIN ON CORRECTED DATASET
=============================================================================
Trains the 9-class XGBoost model on the corrected dataset (generated by the
real AeroTwin physics engine). Feature list and NOISE_STD are read from the
dataset metadata so there is no hardcoding.
=============================================================================
"""
import os
import json
import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.metrics import (
    accuracy_score, f1_score, classification_report, confusion_matrix
)
from sklearn.utils.class_weight import compute_sample_weight

DATA_DIR   = r"e:\PRATIBIMB\DATASET\features"
OUTPUT_DIR = r"e:\PRATIBIMB\FAULT DETECTION"

FAULT_NAMES = [
    "NORMAL", "MISFIRE", "INJECTOR_ABNORMALITY", "CODING_DEGRADATION",
    "LUBRICATION_ISSUE", "SENSOR_DRIFT_FAILURE", "COMBUSTION_INSTABILITY",
    "OVERHEATING", "ABNORMAL_VIBRATION",
]


def load_data():
    train_df = pd.read_parquet(os.path.join(DATA_DIR, "train.parquet"))
    val_df   = pd.read_parquet(os.path.join(DATA_DIR, "validation.parquet"))
    test_df  = pd.read_parquet(os.path.join(DATA_DIR, "test.parquet"))
    with open(os.path.join(DATA_DIR, "dataset_metadata.json"), "r") as f:
        meta = json.load(f)
    return train_df, val_df, test_df, meta


def run_training():
    train_df, val_df, test_df, meta = load_data()

    # Feature list from metadata — no hardcoding
    groups = meta["feature_groups"]
    feat_list = (
        groups["environment"]
        + groups["commands"]
        + groups["sensors"]
        + groups["vibration"]
        + groups["physics_residuals"]
        + groups["normalized_residuals"]
        + groups["trends"]
        + groups["rolling_statistics"]
    )
    # Deduplicate preserving order, drop any column not in dataframe
    seen = set()
    features = []
    for f in feat_list:
        if f in train_df.columns and f not in seen:
            seen.add(f)
            features.append(f)

    print("=" * 70)
    print("AEROTWIN-4: XGBOOST FAULT CLASSIFIER — CORRECTED REAL-PHYSICS DATASET")
    print("=" * 70)
    print(f"  Train: {len(train_df)} windows  |  Val: {len(val_df)}  |  Test: {len(test_df)}")
    print(f"  Features: {len(features)}")
    print(f"  Dataset note: {meta.get('generation_note', '')}")
    print()

    # Class distribution
    print("Class distribution (train):")
    for fc, fn in enumerate(FAULT_NAMES):
        n = (train_df["fault_class"] == fc).sum()
        print(f"  {fn:<30}: {n}")
    print()

    y_train = train_df["fault_class"].values
    y_val   = val_df["fault_class"].values
    y_test  = test_df["fault_class"].values

    X_train = train_df[features].values
    X_val   = val_df[features].values
    X_test  = test_df[features].values

    # Compute sample weights to handle class imbalance
    sample_weights = compute_sample_weight("balanced", y_train)

    clf = xgb.XGBClassifier(
        n_estimators=700,
        max_depth=7,
        learning_rate=0.03,
        subsample=0.80,
        colsample_bytree=0.75,
        min_child_weight=3,
        reg_alpha=0.10,
        reg_lambda=2.0,
        gamma=0.05,
        objective="multi:softprob",
        num_class=9,
        eval_metric="mlogloss",
        early_stopping_rounds=50,
        random_state=42,
        n_jobs=-1,
        tree_method="hist",
    )

    print("[*] Training XGBoost model...")
    clf.fit(
        X_train, y_train,
        sample_weight=sample_weights,
        eval_set=[(X_val, y_val)],
        verbose=50,
    )

    best_iter = clf.best_iteration if hasattr(clf, "best_iteration") and clf.best_iteration else 500
    print(f"\n[OK] Best iteration: {best_iter}")

    # Evaluate
    y_pred = clf.predict(X_test)
    acc    = accuracy_score(y_test, y_pred)
    macro_f1 = f1_score(y_test, y_pred, average="macro", zero_division=0)

    print(f"\n=== Test Set Results ===")
    print(f"  Accuracy:  {acc*100:.2f}%")
    print(f"  Macro F1:  {macro_f1:.4f}")
    print()
    print(classification_report(y_test, y_pred, target_names=FAULT_NAMES, digits=3, zero_division=0))

    # Confusion matrix
    cm = confusion_matrix(y_test, y_pred)
    print("Confusion Matrix (rows=true, cols=predicted):")
    header = f"{'':>28}" + "".join(f"{n[:6]:>8}" for n in FAULT_NAMES)
    print(header)
    for i, row in enumerate(cm):
        rowstr = f"{FAULT_NAMES[i]:>28}" + "".join(f"{v:>8}" for v in row)
        print(rowstr)

    # Feature importance
    print("\n=== Top 15 Feature Importances ===")
    booster = clf.get_booster()
    scores  = booster.get_score(importance_type="gain")
    # Map f-indices to names
    fname_map = {f"f{i}": name for i, name in enumerate(features)}
    named_scores = {fname_map.get(k, k): v for k, v in scores.items()}
    top15 = sorted(named_scores.items(), key=lambda x: x[1], reverse=True)[:15]
    for feat, gain in top15:
        print(f"  {feat:<40}: {gain:.1f}")

    # Save model
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    model_path = os.path.join(OUTPUT_DIR, "best_xgboost_fault_detector.json")
    clf.save_model(model_path)
    print(f"\n[OK] Model saved: {model_path}")

    # Save feature metadata (read by xgboost_inference.py)
    meta_out = {
        "features": features,
        "target_names": FAULT_NAMES,
        "noise_std": meta.get("noise_std_calibrated", {}),
        "benchmark_results": [{
            "model_name": "Model C: Full Physics Digital Twin (Corrected Real-Physics Dataset)",
            "num_features": len(features),
            "best_iteration": best_iter,
            "accuracy": acc,
            "macro_f1": macro_f1,
            "confusion_matrix": cm.tolist(),
        }],
    }
    meta_path = os.path.join(OUTPUT_DIR, "xgboost_model_features.json")
    with open(meta_path, "w") as f:
        json.dump(meta_out, f, indent=2)
    print(f"[OK] Feature metadata saved: {meta_path}")

    return acc, macro_f1


if __name__ == "__main__":
    run_training()
